#!/usr/bin/env node

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import crypto from 'crypto';
import { spawn } from 'child_process';

// Simple build script to:
// - Scan src for .svg imports
// - Rasterize each referenced .svg to a .png in a build folder
// - Maintain a manifest JSON with content hashes so unchanged svgs are skipped
//
// NOTE: This uses the `resvg` CLI if available, otherwise falls back to `rsvg-convert` or `inkscape`.

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const projectRoot = path.resolve(__dirname, '..');
// Operate on the prebuild-staged sources so that Vite sees already-processed
// imports and helper modules.
const prebuildRoot = path.join(projectRoot, 'prebuild');
const srcDir = path.join(prebuildRoot, 'src');
// Keep rasterized PNGs and manifest inside prebuild to keep build artifacts
// local to the staging area.
const outputDir = path.join(prebuildRoot, 'rasterized-svgs');
const manifestPath = path.join(outputDir, 'manifest.json');

function log(...args) {
  console.log('[rasterize-svgs]', ...args);
}

function ensureDir(dir) {
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
}

function hashFile(filePath) {
  const buf = fs.readFileSync(filePath);
  return crypto.createHash('sha1').update(buf).digest('hex');
}

function loadManifest() {
  if (!fs.existsSync(manifestPath)) return {};
  try {
    return JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  } catch {
    return {};
  }
}

function saveManifest(manifest) {
  ensureDir(outputDir);
  fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2), 'utf8');
}

function writePreloadHelper(svgFiles) {
  // Generate a JS helper that lets the runtime decide whether to ignore
  // preloading of a given asset string because it has been moved into the
  // SVG UI atlas.
  const stems = Array.from(
    new Set(svgFiles.map((p) => path.basename(p, '.svg'))),
  ).sort();

  const helperPath = path.join(prebuildRoot, 'src', 'js', 'svg_atlas_preload_helper.js');

  const header = `// AUTO-GENERATED by scripts/rasterize-svgs.mjs
// Do not edit by hand. This file maps SVG-based UI assets that have been
// rasterized and packed into the svg-ui-atlas, so the preloader can skip
// loading their original SVG URLs in production builds.

`;

  const body = `
export const ATLAS_SVG_STEMS = new Set(${JSON.stringify(stems, null, 2)});

/**
 * Returns true if the given asset string is a redundant standalone PNG for an
 * atlas-backed UI asset (already in svg-ui-atlas).
 */
export function shouldIgnorePreloadAsset(asset) {
  if (typeof asset !== 'string') return false;

  // Only apply this optimisation in production builds. In dev, always preload
  // so authoring works predictably. This relies on Vite providing
  // import.meta.env.PROD in the client bundle.
  if (import.meta && import.meta.env && !import.meta.env.PROD) {
    return false;
  }

  const lastSlash = asset.lastIndexOf('/');
  let filename = lastSlash >= 0 ? asset.slice(lastSlash + 1) : asset;
  // Strip query/hash
  const q = filename.search(/[?#]/);
  if (q !== -1) filename = filename.slice(0, q);

  const lower = filename.toLowerCase();
  // Only skip standalone PNG preloads (transform-svg-imports rewrites atlas assets to .png).
  // Never skip .svg URLs: ignored assets stay as SVG, and a stem can be in the atlas because
  // another file imported the same SVG without rasterize: ignore.
  if (!lower.endsWith('.png')) {
    return false;
  }
  const base = filename.slice(0, -4);

  // Match stems like "dialog-inset" against names like:
  // - "dialog-inset.png"
  // - "dialog-inset-somehash.png"
  for (const stem of ATLAS_SVG_STEMS) {
    if (base === stem || base.startsWith(stem + '-')) {
      return true;
    }
  }

  return false;
}

/**
 * Tube / Animate exports reference packed textures by **bare filename** (e.g.
 * \`main_btn9slicehover.png\`). Those names are resolved via the tube JSON, not
 * as standalone \`Assets.load()\` URLs. Vite \`import img from '…'\` always yields
 * a string containing \`/\` (or \`http\`), so we only skip path-less bare names.
 *
 * @param {unknown} asset
 * @returns {boolean}
 */
export function shouldSkipBareFilenamePreload(asset) {
  if (typeof asset !== 'string') return false;
  const s = asset.trim();
  if (!s) return false;
  if (s.startsWith('data:') || s.startsWith('blob:')) return false;
  if (/^https?:\\/\\//i.test(s)) return false;
  if (s.includes('/') || s.includes('\\\\')) return false;
  return /\\.(png|jpe?g|webp|gif|mp3|ogg|wav|m4a)$/i.test(s);
}
`;

  ensureDir(path.dirname(helperPath));
  fs.writeFileSync(helperPath, header + body, 'utf8');
  log(`Wrote preload helper to ${path.relative(projectRoot, helperPath)}`);
}

// Find all svg imports in js/ts source files under src
function findSvgImports() {
  /** @type {Set<string>} */
  const svgPaths = new Set();

  /** @param {string} dir */
  function walk(dir) {
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    for (const entry of entries) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(full);
      } else if (entry.isFile() && /\.(js|jsx|ts|tsx)$/.test(entry.name)) {
        const rawContent = fs.readFileSync(full, 'utf8');

        // First pass on raw content: detect imports that should be ignored for
        // the atlas, based on a trailing "// rasterize: ignore" comment.
        /** @type {Set<string>} */
        const ignoreSet = new Set();
        const ignoreImportRe = /import\s+[^'"]*['"]([^'"]+\.svg)['"][^\n]*rasterize:\s*ignore[^\n]*/g;
        const ignoreRequireRe = /require\(\s*['"]([^'"]+\.svg)['"]\s*\)[^\n]*rasterize:\s*ignore[^\n]*/g;
        let im;
        while ((im = ignoreImportRe.exec(rawContent))) {
          const rel = im[1];
          if (rel.startsWith('.')) {
            const abs = path.resolve(path.dirname(full), rel);
            ignoreSet.add(abs);
          }
        }
        while ((im = ignoreRequireRe.exec(rawContent))) {
          const rel = im[1];
          if (rel.startsWith('.')) {
            const abs = path.resolve(path.dirname(full), rel);
            ignoreSet.add(abs);
          }
        }

        let content = rawContent;

        // Strip block comments /* ... */ and line comments // ... so we don't
        // pick up commented-out imports.
        content = content.replace(/\/\*[\s\S]*?\*\//g, '');
        content = content
          .split('\n')
          .map(line => {
            const idx = line.indexOf('//');
            return idx === -1 ? line : line.slice(0, idx);
          })
          .join('\n');

        // crude but effective import/require matcher for *.svg
        const importRe = /import\s+[^'"]*['"]([^'"]+\.svg)['"]/g;
        const requireRe = /require\(\s*['"]([^'"]+\.svg)['"]\s*\)/g;
        let m;
        while ((m = importRe.exec(content))) {
          const rel = m[1];
          if (rel.startsWith('.')) {
            const abs = path.resolve(path.dirname(full), rel);
            // Skip imports explicitly marked to ignore for atlas processing
            if (ignoreSet.has(abs)) continue;
            if (fs.existsSync(abs)) {
              svgPaths.add(abs);
            }
          }
        }
        while ((m = requireRe.exec(content))) {
          const rel = m[1];
          if (rel.startsWith('.')) {
            const abs = path.resolve(path.dirname(full), rel);
            // Skip requires explicitly marked to ignore for atlas processing
            if (ignoreSet.has(abs)) continue;
            if (fs.existsSync(abs)) {
              svgPaths.add(abs);
            }
          }
        }
      }
    }
  }

  walk(srcDir);

  return Array.from(svgPaths);
}

// Choose an available rasterizer CLI
async function detectRasterizer() {
  const candidates = [
    { cmd: 'resvg-js', args: (input, output) => [input, output] },
    { cmd: 'resvg', args: (input, output) => [input, output] },
    { cmd: 'rsvg-convert', args: (input, output) => ['-o', output, input] },
    { cmd: 'inkscape', args: (input, output) => [input, '--export-type=png', `--export-filename=${output}`] },
  ];

  function which(cmd) {
    return new Promise(resolve => {
      const child = spawn(process.platform === 'win32' ? 'where' : 'which', [cmd]);
      child.on('close', code => resolve(code === 0));
    });
  }

  for (const c of candidates) {
    // eslint-disable-next-line no-await-in-loop
    const ok = await which(c.cmd);
    if (ok) return c;
  }
  return null;
}

function runCommand(cmd, args) {
  return new Promise((resolve, reject) => {
    const child = spawn(cmd, args, { stdio: 'inherit' });
    child.on('error', reject);
    child.on('close', code => {
      if (code === 0) resolve();
      else reject(new Error(`${cmd} exited with code ${code}`));
    });
  });
}

async function main() {
  ensureDir(outputDir);

  if (!fs.existsSync(srcDir)) {
    log(`Prebuild src directory not found at ${srcDir}.`);
    log('Make sure scripts/prebuild.mjs has been run before rasterize-svgs.');
    process.exit(1);
  }

  let manifest = loadManifest();
  const svgFiles = findSvgImports();

  if (svgFiles.length === 0) {
    log('No SVG imports found under src.');

    // If there are no SVG imports anymore, clean out any old PNGs and manifest
    // entries so they don't get picked up by TexturePacker.
    const existingPngs = fs
      .readdirSync(outputDir)
      .filter((name) => name.toLowerCase().endsWith('.png'));
    for (const name of existingPngs) {
      const full = path.join(outputDir, name);
      fs.unlinkSync(full);
    }
    manifest = {};
    saveManifest(manifest);
    writePreloadHelper(svgFiles);
    return;
  }

  log(`Found ${svgFiles.length} SVG imports.`);

  // Build a set of current SVG relative paths (from project root)
  const currentSvgRel = new Set(svgFiles.map((p) => path.relative(projectRoot, p)));

  // Remove manifest entries (and their PNGs) that no longer correspond to any
  // existing SVG import.
  for (const rel of Object.keys(manifest)) {
    if (!currentSvgRel.has(rel)) {
      const entry = manifest[rel];
      if (entry && entry.png) {
        const pngPathAbs = path.join(projectRoot, entry.png);
        if (fs.existsSync(pngPathAbs)) {
          fs.unlinkSync(pngPathAbs);
          log(`Removed stale rasterized PNG for removed SVG: ${path.relative(projectRoot, pngPathAbs)}`);
        }
      }
      delete manifest[rel];
    }
  }

  const rasterizer = await detectRasterizer();
  if (!rasterizer) {
    log('ERROR: No SVG rasterizer found. Please install one of: resvg, rsvg-convert, inkscape and ensure it is on your PATH.');
    process.exit(1);
  }

  log(`Using rasterizer: ${rasterizer.cmd}`);

  let converted = 0;
  let skipped = 0;

  for (const svgPath of svgFiles) {
    const relFromRoot = path.relative(projectRoot, svgPath);
    const hash = hashFile(svgPath);

    const existing = manifest[relFromRoot];
    const needsUpdate = !existing || existing.hash !== hash;

    const baseName = path.basename(svgPath, '.svg');
    const pngName = `${baseName}.png`;
    const pngPath = path.join(outputDir, pngName);

    if (!needsUpdate && fs.existsSync(pngPath)) {
      skipped++;
      continue;
    }

    log(`Rasterizing ${relFromRoot} -> ${path.relative(projectRoot, pngPath)}`);

    const args = rasterizer.args(svgPath, pngPath);
    try {
      // eslint-disable-next-line no-await-in-loop
      await runCommand(rasterizer.cmd, args);
      manifest[relFromRoot] = {
        hash,
        png: path.relative(projectRoot, pngPath),
        updatedAt: new Date().toISOString(),
      };
      converted++;
    } catch (err) {
      log(`Failed to rasterize ${relFromRoot}:`, err.message);
    }
  }

  saveManifest(manifest);

  log(`Done. Converted: ${converted}, skipped (unchanged): ${skipped}.`);
  log(`Manifest written to ${path.relative(projectRoot, manifestPath)}`);

  // As an extra safety net, remove any stray PNGs in the output directory that
  // are not referenced by the current manifest anymore.
  const referencedPngRel = new Set(
    Object.values(manifest)
      .map((entry) => entry && entry.png)
      .filter(Boolean),
  );
  const existingPngs = fs
    .readdirSync(outputDir)
    .filter((name) => name.toLowerCase().endsWith('.png'));
  for (const name of existingPngs) {
    const full = path.join(outputDir, name);
    const relFromRoot = path.relative(projectRoot, full);
    if (!referencedPngRel.has(relFromRoot)) {
      fs.unlinkSync(full);
      log(`Removed unreferenced PNG in rasterized-svgs: ${relFromRoot}`);
    }
  }

  // Generate the JS helper that lets the runtime preloader skip SVGs that have
  // been moved into the atlas (always rewrite — includes shouldSkipBareFilenamePreload).
  writePreloadHelper(svgFiles);

  // After rasterizing, build a TexturePacker atlas from all generated PNGs.
  // Output goes into prebuild/src/tube so the game can load it via the staged root.
  const tubeDir = path.join(prebuildRoot, 'src', 'tube');
  ensureDir(tubeDir);

  // Check that we actually have some PNGs to pack
  const pngFiles = fs
    .readdirSync(outputDir)
    .filter((name) => name.toLowerCase().endsWith('.png'));

  if (pngFiles.length === 0) {
    log('No rasterized PNGs found to pack into an atlas, skipping TexturePacker step.');
    return;
  }

  // Detect TexturePacker CLI
  const tpWhich = await new Promise((resolve) => {
    const child = spawn(process.platform === 'win32' ? 'where' : 'which', ['texturepacker']);
    child.on('close', (code) => resolve(code === 0));
  });

  if (!tpWhich) {
    log('TexturePacker not found on PATH, skipping atlas generation.');
    return;
  }

  const atlasPng = path.join(tubeDir, 'svg-ui-atlas.png');
  const atlasJson = path.join(tubeDir, 'svg-ui-atlas.json');

  log(
    `Running TexturePacker to build atlas: ${path.relative(
      projectRoot,
      atlasPng,
    )} / ${path.relative(projectRoot, atlasJson)}`,
  );

  const tpArgs = [
    '--data',
    atlasJson,
    '--format',
    'json',
    // Preserve original transparent padding in source images
    '--trim-mode',
    'None',
    // Add padding/extrusion between sprites to avoid 9-slice bleeding
    '--shape-padding',
    '4',
    '--border-padding',
    '2',
    '--extrude',
    '2',
    '--max-size',
    '4096',
    '--sheet',
    atlasPng,
    '--reduce-border-artifacts',
    outputDir,
    '--size-constraints',
    'POT',
    '--force-publish',
  ];

  try {
    await runCommand('texturepacker', tpArgs);
    log('TexturePacker atlas generation completed.');
  } catch (err) {
    log('TexturePacker atlas generation failed:', err.message);
    return;
  }

  // Compress the atlas PNG using pngquant if available, similar to tubewatch.py.
  try {
    const pngquantPath = await new Promise((resolve) => {
      const child = spawn(process.platform === 'win32' ? 'where' : 'which', ['pngquant']);
      let found = false;
      child.on('close', (code) => {
        resolve(code === 0);
      });
    });

    // pngquantPath here is boolean (found or not)
    if (!pngquantPath) {
      log('pngquant not found on PATH; skipping atlas PNG compression.');
      return;
    }

    if (!fs.existsSync(atlasPng)) {
      log(`Atlas PNG not found for compression: ${atlasPng}`);
      return;
    }

    const statsBefore = fs.statSync(atlasPng);
    const originalSize = statsBefore.size;

    const tempPath = `${atlasPng}.tmp`;
    const args = [
      '--force',
      '--quality',
      '65-80',
      '--colors',
      '256',
      '--output',
      tempPath,
      atlasPng,
    ];

    log('Running pngquant on atlas PNG...');
    await runCommand('pngquant', args);

    if (fs.existsSync(tempPath)) {
      fs.replaceSync
        ? fs.replaceSync(tempPath, atlasPng)
        : fs.renameSync(tempPath, atlasPng);

      const statsAfter = fs.statSync(atlasPng);
      const newSize = statsAfter.size;
      const reduction = ((originalSize - newSize) / originalSize) * 100;
      log(
        `Atlas PNG compressed with pngquant: ${originalSize.toLocaleString()} → ${newSize.toLocaleString()} bytes (${reduction.toFixed(
          1,
        )}% reduction)`,
      );
    } else {
      log('pngquant did not produce a temp output file; atlas PNG left unmodified.');
    }
  } catch (err) {
    log('Warning: pngquant compression of atlas PNG failed:', err.message);
  }
}

main().catch(err => {
  console.error('[rasterize-svgs] Fatal error:', err);
  process.exit(1);
});

